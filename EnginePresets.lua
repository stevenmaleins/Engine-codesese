local function deepCopy(value)
	if type(value) ~= "table" then
		return value
	end
	local result = {}
	for key, child in pairs(value) do
		result[key] = deepCopy(child)
	end
	return result
end

local byName = {}
for _, preset in ipairs(PresetData) do
	byName[preset.name] = preset
end

local EnginePresets = {}

function EnginePresets.GetCount(includeHidden)
	if includeHidden then
		return #PresetData
	end
	local count = 0
	for _, preset in ipairs(PresetData) do
		if not preset.hidden then
			count += 1
		end
	end
	return count
end

function EnginePresets.GetAll(includeHidden)
	local result = {}
	for _, preset in ipairs(PresetData) do
		if includeHidden or not preset.hidden then
			table.insert(result, deepCopy(preset))
		end
	end
	return result
end

function EnginePresets.GetByName(name)
	local preset = byName[name]
	if not preset then
		return nil
	end
	return deepCopy(preset)
end

function EnginePresets.GetByIndex(index, includeHidden)
	local list = EnginePresets.GetAll(includeHidden)
	if index < 1 or index > #list then
		return nil
	end
	return list[index]
end

function EnginePresets.DeepCopy(value)
	return deepCopy(value)
end

return EnginePresets
